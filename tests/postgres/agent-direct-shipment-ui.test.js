'use strict';

process.env.NODE_ENV='test';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');

test('a phone owner sees plan locks and completes a real direct purchase, supplier dispatch, invoice and customer tracking',{timeout:720000},async t=>{
  const f=await require('../helpers/agent-workflow-fixture').fixture(t,{units:20});
  const {db,ctx}=f;
  await db.query("UPDATE accounts SET created_at=(now()-interval '30 days')::text WHERE id=$1",[f.owner.accountId]);
  await f.subscribe('starter');
  await require('../../src/operations/postgres-commerce').linkSupplierItem(db,ctx,{supplierId:'fixture-supplier',skuId:f.item.skuIds[0],
    lastUnitCost:'7.50',purchaseUnit:'unit',unitsPerPurchaseUnit:1,minimumOrderQuantity:1,orderMultiple:1});
  const order=await f.workflows.createSalesOrder(db,ctx,{customerId:'fixture-customer',deliveryMethod:'SHIP',fulfillmentLocationId:f.location.id,
    idempotencyKey:randomUUID(),lines:[{skuId:f.item.skuIds[0],quantity:2,unitPriceMinor:1500}]});
  const app=require('../../src/postgres-app').createPostgresApp({database:db,env:'test',sessionSecret:randomUUID()});
  const server=await new Promise(resolve=>{const handle=app.listen(0,'127.0.0.1',()=>resolve(handle));});
  const browser=await require('playwright').chromium.launch();
  f.cleanup(async()=>{await browser.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));await app.locals.sessionStore.close();});
  const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const origin='http://127.0.0.1:'+server.address().port;
  const navigate=async click=>Promise.all([page.waitForNavigation(),click()]);
  await page.goto(origin+'/login');
  await page.locator('[name=email]').fill(f.email);
  await page.locator('[name=password]').fill(f.password);
  await navigate(()=>page.locator('button[type=submit]').click());
  await page.goto(origin+'/autopilot/direct-shipments');
  assert.match(await page.locator('main').innerText(),/New supplier-direct purchases require Growth/);
  assert.equal(await page.getByRole('button',{name:'Prepare exact supplier purchase draft',exact:true}).count(),0);
  await f.subscribe('growth');
  await page.goto(origin+'/orders/'+order.salesOrderId);
  await navigate(()=>page.getByRole('link',{name:'Prepare supplier-direct purchase',exact:true}).click());
  await page.locator('select[name=supplierId]').selectOption('fixture-supplier');
  await navigate(()=>page.getByRole('button',{name:'Review exact customer goods',exact:true}).click());
  await page.locator('input[name="lines[0][quantity]"]').fill('2');
  await navigate(()=>page.getByRole('button',{name:'Prepare exact supplier purchase draft',exact:true}).click());
  const directId=new URL(page.url()).pathname.split('/').pop();
  assert.match(await page.locator('main').innerText(),/\$7\.50/);
  assert.equal(await page.locator('[name=routine]').count(),0);
  fs.mkdirSync(path.resolve('output'),{recursive:true});
  await page.screenshot({path:path.resolve('output/agent-direct-purchase-phone.png'),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await navigate(()=>page.getByRole('button',{name:'Approve this exact purchase and destination',exact:true}).click());
  const placement=page.locator('form[action="/autopilot/direct-shipments/'+directId+'/place"]');
  await placement.locator('[name=externalReference]').fill('Supplier confirmed exact customer destination, reference PHONE-1');
  await placement.locator('[name=sentExternally]').check();
  await navigate(()=>placement.getByRole('button',{name:'Record purchase placed with supplier',exact:true}).click());
  const capture=page.locator('form[action="/autopilot/direct-shipments/'+directId+'/capture"]');
  await capture.locator('[name=supplierReference]').fill('PHONE-DISPATCH-1');
  await capture.locator('[name=shippedAt]').fill(new Date(Date.now()-1000).toISOString());
  await capture.locator('[name=carrier]').fill('UPS');
  await capture.locator('[name=trackingNumber]').fill('1Z999AA10123456784');
  await capture.locator('input[name="lines[0][quantity]"]').fill('2');
  await capture.locator('[name=actualShipment]').check();
  await navigate(()=>capture.getByRole('button',{name:'Prepare dispatch review',exact:true}).click());
  await navigate(()=>page.getByRole('button',{name:'Record this shipment, customer invoice and supplier cost',exact:true}).click());
  assert.match(await page.locator('main').innerText(),/Purchase status received/);
  await navigate(()=>page.getByRole('link',{name:/^SHP-/}).click());
  const content=await page.locator('main').innerText();
  assert.match(content,/Supplier-direct dispatch/);
  assert.match(content,/1Z999AA10123456784/);
  assert.match(content,/Parcel item/);
  assert.doesNotMatch(content,/Add an address to the dispatch warehouse/);
  await page.screenshot({path:path.resolve('output/agent-direct-tracking-phone.png'),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  assert.equal(await f.balance(),20);
});
