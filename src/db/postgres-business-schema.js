'use strict';

const crypto = require('node:crypto');
const { openDatabase } = require('./index');

const INTERNAL_TABLES = new Set(['sqlite_sequence']);

function quote(identifier) {
  return `"${String(identifier).replaceAll('"', '""')}"`;
}

function constraintName(table, foreignKey) {
  const signature = `${table}:${foreignKey.from.join(',')}:${foreignKey.table}:${foreignKey.to.join(',')}`;
  return `fk_${table}_${crypto.createHash('sha256').update(signature).digest('hex').slice(0, 16)}`;
}

function foreignKeys(database, table) {
  const groups = new Map();
  for (const row of database.prepare(`PRAGMA foreign_key_list(${quote(table)})`).all()) {
    if (!groups.has(row.id)) groups.set(row.id, { table: row.table, from: [], to: [], onUpdate: row.on_update, onDelete: row.on_delete });
    const group = groups.get(row.id);
    group.from[row.seq] = row.from;
    group.to[row.seq] = row.to;
  }
  return [...groups.values()];
}

function stripReferences(statement) {
  return statement.replace(/\s+REFERENCES\s+(?:"[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s*\([^)]*\)(?:\s+ON\s+UPDATE\s+(?:SET\s+NULL|SET\s+DEFAULT|CASCADE|RESTRICT|NO\s+ACTION))?(?:\s+ON\s+DELETE\s+(?:SET\s+NULL|SET\s+DEFAULT|CASCADE|RESTRICT|NO\s+ACTION))?/gi, '');
}

function translate(statement) {
  return stripReferences(statement)
    .replace(/^(\s*)overlaps(\s+)/gim, '$1"overlaps"$2')
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bTEXT\s+NOT\s+NULL\s+COLLATE\s+NOCASE\b/gi, 'CITEXT NOT NULL')
    .replace(/\bTEXT\s+COLLATE\s+NOCASE\b/gi, 'CITEXT')
    .replace(/\s+COLLATE\s+NOCASE\b/gi, '')
    .replace(/\bIFNULL\s*\(/gi, 'COALESCE(')
    .replace(/\bBLOB\b/gi, 'BYTEA')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bAUTOINCREMENT\b/gi, '')
    .replace(/CREATE\s+TABLE\s+(?!IF\s+NOT\s+EXISTS)/i, 'CREATE TABLE IF NOT EXISTS ')
    .replace(/CREATE\s+(UNIQUE\s+)?INDEX\s+(?!IF\s+NOT\s+EXISTS)/i, 'CREATE $1INDEX IF NOT EXISTS ');
}

function immutableTriggers(database) {
  const statements = [];
  for (const row of database.prepare(`SELECT name, tbl_name AS tableName, sql FROM sqlite_master
      WHERE type = 'trigger' AND sql LIKE '%RAISE(ABORT,%' ORDER BY name`).all()) {
    const operation = /BEFORE\s+(UPDATE|DELETE)/i.exec(row.sql)?.[1]?.toUpperCase();
    const message = /RAISE\s*\(\s*ABORT\s*,\s*'([^']+)'\s*\)/i.exec(row.sql)?.[1];
    if (!operation || !message) continue;
    statements.push(`DROP TRIGGER IF EXISTS ${quote(row.name)} ON ${quote(row.tableName)};`);
    statements.push(`CREATE TRIGGER ${quote(row.name)} BEFORE ${operation} ON ${quote(row.tableName)}
      FOR EACH ROW EXECUTE FUNCTION stockchief_forbid_change(${JSON.stringify(message)});`);
  }
  return statements;
}

function derivedDataStatements() {
  return [`ALTER TABLE search_documents ADD COLUMN IF NOT EXISTS search_vector tsvector
    GENERATED ALWAYS AS (to_tsvector('simple', COALESCE(title, '') || ' ' || COALESCE(identifiers, '') || ' ' || COALESCE(body, ''))) STORED;`,
  `CREATE INDEX IF NOT EXISTS idx_search_documents_vector ON search_documents USING GIN(search_vector);`,
  `CREATE OR REPLACE FUNCTION stockchief_refresh_item_catalog_rollup(target_item TEXT) RETURNS void LANGUAGE plpgsql AS $$
   BEGIN
     INSERT INTO item_catalog_rollups(workspace_id,item_id,sku_count,first_sku_id,first_sku_code,first_sku_position,updated_at)
     SELECT i.workspace_id,i.id,COUNT(s.id),
       (SELECT id FROM skus WHERE item_id=i.id ORDER BY position,id LIMIT 1),
       (SELECT code FROM skus WHERE item_id=i.id ORDER BY position,id LIMIT 1),
       (SELECT position FROM skus WHERE item_id=i.id ORDER BY position,id LIMIT 1),
       to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
     FROM items i LEFT JOIN skus s ON s.item_id=i.id WHERE i.id=target_item GROUP BY i.id
     ON CONFLICT(item_id) DO UPDATE SET sku_count=EXCLUDED.sku_count,first_sku_id=EXCLUDED.first_sku_id,
       first_sku_code=EXCLUDED.first_sku_code,first_sku_position=EXCLUDED.first_sku_position,updated_at=EXCLUDED.updated_at;
   END; $$;`,
  `CREATE OR REPLACE FUNCTION stockchief_sku_rollup_trigger() RETURNS trigger LANGUAGE plpgsql AS $$
   BEGIN
     IF TG_OP <> 'INSERT' THEN PERFORM stockchief_refresh_item_catalog_rollup(OLD.item_id); END IF;
     IF TG_OP <> 'DELETE' AND (TG_OP = 'INSERT' OR NEW.item_id IS DISTINCT FROM OLD.item_id) THEN
       PERFORM stockchief_refresh_item_catalog_rollup(NEW.item_id);
     ELSIF TG_OP = 'UPDATE' THEN PERFORM stockchief_refresh_item_catalog_rollup(NEW.item_id); END IF;
     IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
   END; $$;`,
  `CREATE TRIGGER stockchief_sku_rollup AFTER INSERT OR UPDATE OR DELETE ON skus
    FOR EACH ROW EXECUTE FUNCTION stockchief_sku_rollup_trigger();`,
  `CREATE OR REPLACE FUNCTION stockchief_refresh_item_location(target_sku TEXT, target_location TEXT, changed_at TEXT) RETURNS void LANGUAGE plpgsql AS $$
   BEGIN
     INSERT INTO item_location_balances(workspace_id,item_id,location_id,on_hand,updated_at)
     SELECT s.workspace_id,s.item_id,target_location,COALESCE(SUM(b.on_hand),0),changed_at
     FROM skus s LEFT JOIN balances b ON b.sku_id=s.id AND b.location_id=target_location
     WHERE s.item_id=(SELECT item_id FROM skus WHERE id=target_sku) GROUP BY s.workspace_id,s.item_id
     ON CONFLICT(item_id,location_id) DO UPDATE SET on_hand=EXCLUDED.on_hand,updated_at=EXCLUDED.updated_at;
   END; $$;`,
  `CREATE OR REPLACE FUNCTION stockchief_balance_rollup_trigger() RETURNS trigger LANGUAGE plpgsql AS $$
   BEGIN
     IF TG_OP <> 'INSERT' THEN PERFORM stockchief_refresh_item_location(OLD.sku_id,OLD.location_id,COALESCE(NEW.updated_at,OLD.updated_at)); END IF;
     IF TG_OP <> 'DELETE' THEN PERFORM stockchief_refresh_item_location(NEW.sku_id,NEW.location_id,NEW.updated_at); END IF;
     IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
   END; $$;`,
  `CREATE TRIGGER stockchief_balance_rollup AFTER INSERT OR UPDATE OR DELETE ON balances
    FOR EACH ROW EXECUTE FUNCTION stockchief_balance_rollup_trigger();`,
  `CREATE OR REPLACE FUNCTION stockchief_search_item_trigger() RETURNS trigger LANGUAGE plpgsql AS $$
   BEGIN
     IF TG_OP='DELETE' THEN
       DELETE FROM search_documents WHERE workspace_id=OLD.workspace_id AND
         ((entity_type='item' AND entity_id=OLD.id) OR (entity_type='sku' AND entity_id IN (SELECT id FROM skus WHERE item_id=OLD.id)));
       RETURN OLD;
     END IF;
     INSERT INTO search_documents(workspace_id,entity_type,entity_id,title,identifiers,body,updated_at)
     VALUES (NEW.workspace_id,'item',NEW.id,NEW.name,COALESCE(NEW.base_code,''),COALESCE(NEW.description,'') || ' ' || COALESCE(NEW.unit_label,''),NEW.updated_at)
     ON CONFLICT(workspace_id,entity_type,entity_id) DO UPDATE SET title=EXCLUDED.title,identifiers=EXCLUDED.identifiers,body=EXCLUDED.body,updated_at=EXCLUDED.updated_at;
     UPDATE search_documents d SET title=NEW.name || ' ' || COALESCE(s.variant_label,''),
       body=COALESCE(NEW.description,''),updated_at=NEW.updated_at FROM skus s
       WHERE d.workspace_id=NEW.workspace_id AND d.entity_type='sku' AND d.entity_id=s.id AND s.item_id=NEW.id;
     RETURN NEW;
   END; $$;`,
  `CREATE TRIGGER stockchief_search_items AFTER INSERT OR UPDATE OR DELETE ON items
    FOR EACH ROW EXECUTE FUNCTION stockchief_search_item_trigger();`,
  `CREATE OR REPLACE FUNCTION stockchief_search_sku_trigger() RETURNS trigger LANGUAGE plpgsql AS $$
   BEGIN
     IF TG_OP='DELETE' THEN DELETE FROM search_documents WHERE workspace_id=OLD.workspace_id AND entity_type='sku' AND entity_id=OLD.id; RETURN OLD; END IF;
     INSERT INTO search_documents(workspace_id,entity_type,entity_id,title,identifiers,body,updated_at)
     SELECT NEW.workspace_id,'sku',NEW.id,i.name || ' ' || COALESCE(NEW.variant_label,''),
       NEW.code || ' ' || COALESCE(NEW.barcode,''),COALESCE(i.description,''),NEW.created_at FROM items i WHERE i.id=NEW.item_id
     ON CONFLICT(workspace_id,entity_type,entity_id) DO UPDATE SET title=EXCLUDED.title,identifiers=EXCLUDED.identifiers,body=EXCLUDED.body,updated_at=EXCLUDED.updated_at;
     RETURN NEW;
   END; $$;`,
  `CREATE TRIGGER stockchief_search_skus AFTER INSERT OR UPDATE OR DELETE ON skus
    FOR EACH ROW EXECUTE FUNCTION stockchief_search_sku_trigger();`];
}

function renderBusinessSchema() {
  const database = openDatabase(':memory:');
  try {
    const tables = database.prepare(`SELECT name, sql FROM sqlite_master
      WHERE type = 'table' AND sql IS NOT NULL ORDER BY rowid`).all()
      .filter((row) => !INTERNAL_TABLES.has(row.name) && !row.name.startsWith('search_documents_fts'));
    const indexes = database.prepare(`SELECT name, tbl_name AS tableName, sql FROM sqlite_master
      WHERE type = 'index' AND sql IS NOT NULL ORDER BY name`).all()
      .filter((row) => !row.tableName.startsWith('search_documents_fts'));
    const statements = [
      'CREATE EXTENSION IF NOT EXISTS citext;',
      `CREATE OR REPLACE FUNCTION stockchief_forbid_change() RETURNS trigger LANGUAGE plpgsql AS $$
       BEGIN RAISE EXCEPTION USING MESSAGE = TG_ARGV[0], ERRCODE = 'integrity_constraint_violation'; END;
       $$;`,
      ...tables.map((row) => `${translate(row.sql)};`),
      ...indexes.map((row) => `${translate(row.sql)};`),
    ];
    for (const row of tables) {
      for (const foreignKey of foreignKeys(database, row.name)) {
        const actions = [foreignKey.onUpdate && foreignKey.onUpdate !== 'NO ACTION' ? `ON UPDATE ${foreignKey.onUpdate}` : '',
          foreignKey.onDelete && foreignKey.onDelete !== 'NO ACTION' ? `ON DELETE ${foreignKey.onDelete}` : ''].filter(Boolean).join(' ');
        statements.push(`ALTER TABLE ${quote(row.name)} ADD CONSTRAINT ${quote(constraintName(row.name, foreignKey))}
          FOREIGN KEY (${foreignKey.from.map(quote).join(', ')}) REFERENCES ${quote(foreignKey.table)} (${foreignKey.to.map(quote).join(', ')})
          ${actions} DEFERRABLE INITIALLY DEFERRED;`);
      }
    }
    statements.push(...immutableTriggers(database));
    statements.push(...derivedDataStatements());
    statements.push(`CREATE TABLE IF NOT EXISTS stockchief_migration_runs (
      id TEXT PRIMARY KEY,
      source_fingerprint TEXT NOT NULL UNIQUE,
      source_schema_fingerprint TEXT NOT NULL,
      status TEXT NOT NULL CHECK (status IN ('RUNNING','COMPLETED','FAILED')),
      reconciliation JSONB,
      started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      completed_at TIMESTAMPTZ
    );`);
    return `${statements.join('\n\n')}\n`;
  } finally {
    database.close();
  }
}

module.exports = { renderBusinessSchema, translate, stripReferences };
