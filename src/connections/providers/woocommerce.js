function metadata() {
  return { type: 'woocommerce', name: 'WooCommerce', mark: 'Woo', category: 'selling', authMode: 'application_auth', authMethods:['application_auth','api_keys'], available: true,
    description: 'Connect a WooCommerce store without scripts. StockChief discovers products and receives order webhooks automatically.',
    provides: ['customer orders', 'cancellations', 'fulfillment', 'products and store activity'],
  };
}

function validateInput(input) {
  normalizeStoreUrl(input.storeUrl);
}

function authorizationUrl({ state, input }) {
  const storeUrl = normalizeStoreUrl(input.storeUrl);
  const url = new URL(`${storeUrl}/wc-auth/v1/authorize`);
  url.searchParams.set('app_name', 'StockChief Inventory');
  url.searchParams.set('scope', 'read_write');
  url.searchParams.set('user_id', state);
  url.searchParams.set('return_url', input.returnUri);
  url.searchParams.set('callback_url', input.callbackUri);
  return { url: url.toString(), metadata: { storeUrl } };
}

function credentialsFromCallback(body, metadata) {
  return credentialsFromInput({storeUrl:metadata.storeUrl,consumerKey:body.consumer_key,consumerSecret:body.consumer_secret});
}

function credentialsFromInput(input){
  const storeUrl=normalizeStoreUrl(input.storeUrl);
  const consumerKey=String(input.consumerKey||'').trim(),consumerSecret=String(input.consumerSecret||'').trim();
  if(!/^ck_[a-f0-9]{40}$/i.test(consumerKey)||!/^cs_[a-f0-9]{40}$/i.test(consumerSecret))
    throw new ValidationError('Enter the Consumer Key and Consumer Secret generated by WooCommerce.');
  return {storeUrl,consumerKey,consumerSecret,webhookSecret:crypto.randomBytes(32).toString('base64url')};
}

async function verifyReadOnly({credentials}){
  const products=await api(credentials,'/products?per_page=1');
  if(!Array.isArray(products.body))throw new ValidationError('This address did not return a WooCommerce product catalogue.');
  const currency=await storeCurrency(credentials);
  return {accountId:credentials.storeUrl,accountName:new URL(credentials.storeUrl).hostname,
    capabilities:['read_products','read_inventory','read_orders'],verifiedFact:{currency,checkedAt:new Date().toISOString(),source:'authenticated_woocommerce_api'}};
}

async function storeCurrency(credentials){
  let value;
  try{value=(await api(credentials,'/data/currencies/current')).body?.code;}
  catch(error){
    // Older or customized stores can omit this read-only data endpoint.
    // An authorization failure must never be treated as an absent route.
    if(error.status!==404)throw error;
    value=(await api(credentials,'/settings/general/woocommerce_currency')).body?.value;
  }
  try{return money.code(value);}catch{
    throw new ValidationError('WooCommerce did not return a recognized store currency. This attempt did not import products.');
  }
}

async function api(credentials, path, options = {}) {
  const auth = Buffer.from(`${credentials.consumerKey}:${credentials.consumerSecret}`).toString('base64');
  try{return await jsonRequest(`${credentials.storeUrl}/wp-json/wc/v3${path}`, { ...options,selfHostedStore:true,
    headers: { authorization: `Basic ${auth}`, 'content-type': 'application/json', ...(options.headers || {}) } });
  }catch(error){
    // Self-hosted stores control their error bodies. Do not persist reflected
    // keys, provider bodies or authorization headers in logs or usage receipts.
    const known=error instanceof DomainError;
    const status=known?error.status:([400,401,403,404,409,422,429,503].includes(Number(error.status))?Number(error.status):503);
    const resource=path.startsWith('/products')?'products':path.startsWith('/data/currencies')||path.startsWith('/settings/general/woocommerce_currency')?'currency':path.startsWith('/webhooks')?'webhooks':'api';
    const messages={401:'WooCommerce did not authorize this request. Check that the keys belong to this store and their WordPress user has access.',
      403:'WooCommerce denied access. Check the key permissions and the store’s API security settings.',
      404:resource==='currency'?'The store’s currency could not be read from its WooCommerce API. This attempt did not import products.':
        'The requested WooCommerce information is not available. Check the store address and its REST API setup.',
      409:'WooCommerce reported a conflicting request. Its result must be checked before the operation is repeated.'};
    const safe=new DomainError(known?error.message:messages[status]||'WooCommerce could not complete this API request. Check its REST API access.',
      {status,code:known?error.code:'woocommerce_request_rejected'});
    safe.providerResource=resource;safe.httpStatus=status;
    for(const flag of ['providerOutcomeUncertain','transient','retryable'])if(typeof error[flag]==='boolean')safe[flag]=error[flag];
    for(const field of ['httpStatus','attempts'])if(Number.isSafeInteger(error[field]))safe[field]=error[field];
    throw safe;
  }
}

async function discover({ credentials, onProduct }) {
  const currency=await storeCurrency(credentials);
  const priceMoney=value=>String(value??'').trim()===''?null:{amount:money.toMinor(value,currency),currency};
  const products = [];const output=onProduct?{push:onProduct}:products;
  for (let page = 1; ; page += 1) {
    const response = await api(credentials, `/products?per_page=100&page=${page}`);
    const rows = response.body || [];
    for (const product of rows) {
      if (product.type === 'variable' && product.variations?.length) {
        for (let variantPage = 1; ; variantPage += 1) {
          const variantsResponse = await api(credentials, `/products/${product.id}/variations?per_page=100&page=${variantPage}`);
          const variants = variantsResponse.body || [];
          for (const variant of variants) output.push({ entityType: 'sku', externalId: String(variant.id),
            parentExternalId: String(product.id), code: variant.sku || null,
            displayName: `${product.name}${variant.attributes?.length ? ` / ${variant.attributes.map((a) => a.option).join(' / ')}` : ''}`,
            providerData: { status: variant.status,productStatus:(variant.status||product.status)==='publish'?'ACTIVE':String(variant.status||product.status||'UNKNOWN').toUpperCase(), itemName: product.name,virtual:variant.virtual===true,
              selectedOptions:(variant.attributes||[]).map(a=>({name:a.name||'Option '+a.id,value:a.option})),
              variationName: variant.attributes?.map((a) => a.option).join(' / ') || null,
              priceMoney:priceMoney(variant.price),
              inventoryCounts: variant.manage_stock===true && variant.stock_quantity!=null && Number.isSafeInteger(Number(variant.stock_quantity))
                ? [{ externalLocationId: credentials.storeUrl, state: 'IN_STOCK', quantity: Number(variant.stock_quantity) }]
                : [] } });
          const variantPages = Number(variantsResponse.headers.get('x-wp-totalpages') || 1);
          if (variantPage >= variantPages) break;
        }
      } else output.push({ entityType: 'sku', externalId: String(product.id), code: product.sku || null,
        displayName: product.name, providerData: { status: product.status,productStatus:product.status==='publish'?'ACTIVE':String(product.status||'UNKNOWN').toUpperCase(), itemName: product.name,virtual:product.virtual===true,
          variationName: null,
          priceMoney:priceMoney(product.price),
          inventoryCounts: product.manage_stock===true && product.stock_quantity!=null && Number.isSafeInteger(Number(product.stock_quantity))
            ? [{ externalLocationId: credentials.storeUrl, state: 'IN_STOCK', quantity: Number(product.stock_quantity) }]
            : [] } });
    }
    const pages = Number(response.headers.get('x-wp-totalpages') || 1);
    if (page >= pages) break;
  }
  return { products, locations: [{ entityType: 'location', externalId: credentials.storeUrl,
    displayName: new URL(credentials.storeUrl).hostname, providerData: { kind: 'online_store' } }] };
}

async function registerWebhooks({ credentials, webhookUrl }) {
  const topics = ['order.created', 'order.updated', 'order.deleted', 'product.created', 'product.updated'];
  const existing = [];
  for (let page = 1; ; page += 1) {
    const response = await api(credentials, `/webhooks?per_page=100&page=${page}`);
    existing.push(...(response.body || []));
    if (page >= Number(response.headers.get('x-wp-totalpages') || 1)) break;
  }
  const results = [];
  const used = new Set();
  for (const topic of topics) {
    const current = existing.find((hook) => hook.topic === topic && hook.delivery_url === webhookUrl);
    const payload = { name: `StockChief ${topic}`, topic, delivery_url: webhookUrl,
      secret: credentials.webhookSecret, status: 'active' };
    const { body } = current
      ? await api(credentials, `/webhooks/${current.id}`, { method: 'PUT', body: JSON.stringify(payload) })
      : await api(credentials, '/webhooks', { method: 'POST', body: JSON.stringify(payload) });
    if(!body?.id||body.delivery_url!==webhookUrl||body.topic!==topic||body.status!=='active')
      throw new ValidationError('WooCommerce did not confirm the requested event delivery. Verify that the API key has read/write permission.');
    if (current) used.add(current.id);
    results.push({ topic, id: body.id });
  }
  const stale = existing.filter((hook) => {
    // Other StockChief businesses can legitimately authorize the same store.
    // Manage only this exact destination, never a different tenant or host.
    return hook.delivery_url===webhookUrl&&!used.has(hook.id);
  });
  for (const hook of stale) {
    await api(credentials, `/webhooks/${hook.id}?force=true`, { method: 'DELETE' });
    results.push({ topic: hook.topic, id: hook.id, removedStale: true });
  }
  return results;
}

async function historySummary({ credentials, since }) {
  const response = await api(credentials, `/orders?after=${encodeURIComponent(since)}&per_page=1`);
  return { operationalRecords: Number(response.headers.get('x-wp-total') || (response.body || []).length), periodStart: since };
}

function verifyWebhook({ headers, rawBody, credentials }) {
  const expected = hmacBase64(credentials.webhookSecret, rawBody);
  requireVerified(safeEqual(headers['x-wc-webhook-signature'], expected), 'This webhook did not pass WooCommerce signature verification.');
}

function normalizeNotification({ headers, body, connection }) {
  const topic = String(headers['x-wc-webhook-topic'] || `${headers['x-wc-webhook-resource']}.${headers['x-wc-webhook-event']}`).toLowerCase();
  const delivery = String(headers['x-wc-webhook-delivery-id'] || headers['x-wc-delivery-id'] || `${topic}:${body.id}:${body.date_modified_gmt || body.date_created_gmt}`);
  const occurredAt = body.date_modified_gmt || body.date_created_gmt;
  const version = occurredAt;
  const orderData = { externalOrderId: String(body.id), orderNumber: body.number,sourceSnapshotComplete:true,
      customer: { externalId: body.customer_id ? String(body.customer_id) : undefined,
        name: [body.billing?.first_name, body.billing?.last_name].filter(Boolean).join(' ') || body.billing?.email || 'WooCommerce customer' },
      shippingAddress: postalAddress({ line1: body.shipping?.address_1, line2: body.shipping?.address_2,
        city: body.shipping?.city, region: body.shipping?.state, postalCode: body.shipping?.postcode, country: body.shipping?.country }),
      customerEmail: body.billing?.email,
      externalLocationId: connection?.config?.storeUrl || undefined,
      ...(['order.created','order.updated'].includes(topic)?facts.woocommerce(body):{}) };
  const event = (suffix, type, data = orderData) => ({ eventId: `${delivery}:${suffix}`,
    effectKey:facts.effectKey('woocommerce',suffix,body.id,...(suffix==='snapshot'?[version]:[])), type, version, occurredAt,
    aggregateId: String(body.id), data });
  if (topic === 'order.created') {
    const created = event('created', 'sales_order.created');
    if (body.status === 'completed') return [created, event('fulfilled', 'sales_order.fulfilled', {...orderData,fulfillmentMode:'cumulative'})];
    if (['cancelled', 'failed'].includes(body.status)) return [created, event('cancelled', 'sales_order.cancelled', {
      externalOrderId: String(body.id), reason: `WooCommerce status: ${body.status}` })];
    return [created];
  }
  if (topic === 'order.updated') {
    if (body.status === 'completed') return [event('snapshot', 'sales_order.snapshot'),
      event('fulfilled', 'sales_order.fulfilled', {...orderData,fulfillmentMode:'cumulative'})];
    if (['cancelled', 'failed'].includes(body.status)) return [event('cancelled', 'sales_order.cancelled', {
      externalOrderId: String(body.id), reason: `WooCommerce status: ${body.status}` })];
    if (body.status === 'refunded') {
      const refunds = Array.isArray(body.refunds) && body.refunds.length ? body.refunds : [{ id: `order-${body.id}` }];
      const reported = refunds.map((refund) => event(`refund-${refund.id}`, 'return.reported', {
        externalOrderId: String(body.id), refundId: String(refund.id), currency:body.currency,
        amountMinor:refund.total==null?undefined:Math.abs(money.toMinor(refund.total,body.currency,{signed:true})),
        reason: refund.reason || 'WooCommerce reported a financial refund; physical stock requires confirmation.',
      }));
      return body.date_completed_gmt ? reported : [event('cancelled', 'sales_order.cancelled', {
        externalOrderId: String(body.id), reason: 'WooCommerce order refunded before fulfillment' }), ...reported];
    }
    if (['pending', 'processing', 'on-hold'].includes(body.status)) return [event('snapshot', 'sales_order.snapshot')];
    return [];
  }
  if (topic === 'order.deleted') return [{ eventId: `${delivery}:cancelled`, type: 'sales_order.cancelled', version, occurredAt,
    aggregateId: String(body.id), data: { externalOrderId: String(body.id), reason: 'Deleted in WooCommerce' } }];
  if (topic.startsWith('product.')) return [{ eventId: `${delivery}:product`, type: 'product.changed', version, occurredAt,
    data: { externalProductId: String(body.id), name: body.name, sku: body.sku } }];
  throw new ValidationError(`WooCommerce topic ${topic || '(missing)'} is not supported.`);
}
function normalizeWebhook(input){
 const events=normalizeNotification(input),{body,headers}=input,topic=String(headers['x-wc-webhook-topic']||'');
 if(!['order.created','order.updated'].includes(topic))return events;
 // Woo sends partially refunded orders as completed/processing as well.
 // Financial refunds are independent observations, never physical receipts.
 for(const refund of body.refunds||[]){
  const key=facts.effectKey('woocommerce','refund-'+refund.id,body.id);
  if(events.some(e=>e.effectKey===key))continue;
  events.push({eventId:String(headers['x-wc-webhook-delivery-id']||body.id)+':refund-'+refund.id,effectKey:key,type:'return.reported',
   aggregateId:String(body.id),occurredAt:body.date_modified_gmt,data:{externalOrderId:String(body.id),refundId:String(refund.id),currency:body.currency,
    amountMinor:refund.total==null?undefined:Math.abs(money.toMinor(refund.total,body.currency,{signed:true})),reason:refund.reason||'WooCommerce reported a financial refund; physical stock requires confirmation.'}});
 }
 return events;
}

